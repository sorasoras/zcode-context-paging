import { test, assert, assertEqual } from "./harness.mjs";
import { selectContext } from "../src/policy.mjs";
import { simpleEstimator } from "./fixtures.mjs";
import { stableHash } from "../src/wire.mjs";

// A user message that batches tool results together with reminder text: ZCode does this,
// and it makes the message both a result carrier and a turn start — the seam the policy
// must not cut through.
const mixedCarrierBody = () => ({
	model: "test-model",
	max_tokens: 4096,
	system: [{ type: "text", text: "You are a test harness system prompt. ".repeat(4) }],
	tools: [{ name: "read_file", description: "Read a file.", input_schema: { type: "object", properties: { path: { type: "string" } } } }],
	messages: [
		{ role: "user", content: [{ type: "text", text: "Turn one: inspect the flubber configuration. ".repeat(120) }] },
		{ role: "assistant", content: [
			{ type: "text", text: "Reading the flubber config now. ".repeat(60) },
			{ type: "tool_use", id: "call_1", name: "read_file", input: { path: "flubber.json" } },
		] },
		{ role: "user", content: [
			{ type: "tool_result", tool_use_id: "call_1", content: [{ type: "text", text: "flubber=true" }] },
			{ type: "text", text: "<system-reminder>Plan mode is active.</system-reminder>" },
		] },
		{ role: "user", content: [{ type: "text", text: "Turn two: summarize." }] },
	],
});

const residentOf = (body) => simpleEstimator({
	role: "user",
	content: [body.system.map((block) => block.text).join("\n"), JSON.stringify(body.tools)].join("\n"),
});
const retainedFrom = (body, index) => residentOf(body) + body.messages.slice(index).reduce((sum, m) => sum + simpleEstimator(m), 0);

const danglingIn = (messages) => {
	const seen = new Set();
	const orphans = [];
	for (const message of messages) {
		const blocks = Array.isArray(message.content) ? message.content : [];
		if (message.role === "assistant") for (const block of blocks) if (block?.type === "tool_use") seen.add(block.id);
		for (const block of blocks) if (block?.type === "tool_result" && !seen.has(block.tool_use_id)) orphans.push(block.tool_use_id);
	}
	return orphans;
};

test("a mixed result-carrier turn start is never cut: the use is pulled back", () => {
	const body = mixedCarrierBody();
	// Destination exactly at the retained size of the mixed carrier onward: the eviction
	// loop stops with the boundary ON the mixed message, orphaning call_1's result.
	const budget = retainedFrom(body, 1) + Math.floor(simpleEstimator(body.messages[0]) / 2);
	const trim = retainedFrom(body, 2);
	const result = selectContext({
		body,
		shape: "anthropic",
		budgetTokens: budget,
		trimToTokens: trim,
		state: null,
		estimateMessage: simpleEstimator,
	});
	assertEqual(result.mode, "paged");
	const orphans = danglingIn(result.body.messages);
	assertEqual(orphans, [], "forwarded request must not carry orphaned tool_results");
	const flat = JSON.stringify(result.body.messages);
	assert(flat.includes('"call_1"'), "the repaired slice must still contain the call_1 exchange");
	const notice = result.body.messages[0].content[0].text;
	assert(notice.startsWith("[Context paging notice"), "paged request must carry the notice");
});

test("a remembered frontier that orphans results is repaired and the stale notice discarded", () => {
	const body = mixedCarrierBody();
	const state = {
		frontierIndex: 2,
		frontierHash: stableHash(body.messages[2]),
		noticeText: "[Context paging notice — generated by zcode-context-paging]\nstale notice from the broken cut",
	};
	const result = selectContext({
		body,
		shape: "anthropic",
		budgetTokens: retainedFrom(body, 0) - 10,
		trimToTokens: retainedFrom(body, 2),
		state,
		estimateMessage: simpleEstimator,
	});
	assertEqual(danglingIn(result.body.messages), [], "repaired request must not carry orphaned tool_results");
	const notice = result.body.messages[0].content[0].text;
	assert(!notice.includes("stale notice"), "the stale notice text must not survive a moved boundary");
	assert(result.frontier?.frontierHash === stableHash(body.messages[result.evicted]), "frontier hash must describe the repaired boundary");
});

test("results of aborted calls are stripped block-wise, matched pairs survive", () => {
	const body = {
		model: "test-model",
		max_tokens: 4096,
		system: [{ type: "text", text: "You are a test harness system prompt. ".repeat(4) }],
		tools: [{ name: "read_file", description: "Read a file.", input_schema: { type: "object", properties: { path: { type: "string" } } } }],
		messages: [
			{ role: "user", content: [{ type: "text", text: "Turn one." }] },
			{ role: "assistant", content: [
				{ type: "text", text: "Working. ".repeat(80) },
				{ type: "tool_use", id: "call_2", name: "read_file", input: { path: "widget.json" } },
			] },
			{ role: "user", content: [{ type: "tool_result", tool_use_id: "call_2", content: [{ type: "text", text: "widget=7" }] }] },
			{ role: "user", content: [{ type: "tool_result", tool_use_id: "call_9", content: [{ type: "text", text: "orphaned aborted call" }] }] },
		],
	};
	const result = selectContext({
		body,
		shape: "anthropic",
		budgetTokens: retainedFrom(body, 0) - 10,
		trimToTokens: retainedFrom(body, 2),
		state: null,
		estimateMessage: simpleEstimator,
	});
	const orphans = danglingIn(result.body.messages);
	assertEqual(orphans, [], "unpairable results must be stripped, not forwarded");
	const flat = JSON.stringify(result.body.messages);
	assert(!flat.includes("call_9"), "the aborted call id must not appear in the forwarded request");
	assert(flat.includes('"call_2"') && flat.includes("widget=7"), "the matched call_2 pair must survive intact");
});

test("the repaired boundary is stable across the next request", () => {
	const body = mixedCarrierBody();
	const first = selectContext({
		body,
		shape: "anthropic",
		budgetTokens: retainedFrom(body, 0) - 10,
		trimToTokens: retainedFrom(body, 2),
		state: null,
		estimateMessage: simpleEstimator,
	});
	assert(first.frontier !== undefined, "a paged request must store a frontier");
	const second = selectContext({
		body,
		shape: "anthropic",
		budgetTokens: retainedFrom(body, 0) - 10,
		trimToTokens: retainedFrom(body, 2),
		state: first.frontier,
		estimateMessage: simpleEstimator,
	});
	assertEqual(second.evicted, first.evicted, "the repaired frontier must be reusable as-is");
	assertEqual(danglingIn(second.body.messages), []);
});
